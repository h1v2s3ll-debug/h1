"""
نظام استرجاع الوصول للدعم الفني (لك أنت كمطوّر البرنامج، مو للعميل نفسه).

ليش هذا التصميم بالذات: طلب أصلي كان "يوزر وباسورد ثابتين معروفين للمطوّر
بس" (مثلاً hamza / 2005). المشكلة الحقيقية بهذا: أي رمز ثابت وبسيط (اسم +
سنة ميلاد) يشتغل بنفس القوة على **كل نسخة مثبتة من البرنامج بكل الصيدليات**.
لو تسرب هذا الرمز مرة وحدة بس (حتى بالغلط، أو نسيته مكتوب بمكان، أو حكيته
لشخص وهو حكاها لغيره) - يصير عند أي شخص وصول لكل عميل عندك دفعة وحدة،
بدون أي أثر أو طريقة توقفه.

هذا البديل: رمز الاسترجاع مرتبط ببصمة جهاز العميل المحدد (device_id، نفس
المستخدمة أصلًا بنظام الترخيص) عبر HMAC-SHA256. يعني:
- رمز أي عميل ما يشتغل أبدًا بجهاز عميل ثاني.
- ما تقدر "تتذكره" أو تكتبه بورقة وتستخدمه بأي وقت - لازم تحسبه فعليًا
  لكل حالة (بأداة generate_recovery_code.py المنفصلة اللي عندك بس).
- حتى لو تسرب رمز واحد، ينفع بس لصاحب ذاك الجهاز المحدد.

⚠️ ملاحظة صريحة ومهمة: بما إن هذا برنامج يشتغل بالكامل على جهاز العميل
(بدون سيرفر مركزي يتحقق منه)، أي "سر" مكتوب بالكود المصدري نفسه (المتغير
RECOVERY_SECRET بالأسفل) نظريًا ممكن يوصله شخص عنده خبرة تقنية جيدة ووصل
لملفات البرنامج (حتى لو مُصرّف .exe - أدوات فك التصريف موجودة). هذا قيد
حقيقي على أي نظام استرجاع محلي بالكامل، ما فيه طريقة تخليه "سر مطلق" 100%.
اللي حققناه هنا هو رفع الحاجز التقني والمنطقي لإساءة الاستخدام (يحتاج
مهارة برمجية + وصول لملفات البرنامج + استهداف جهاز معين بالتحديد) بدل
رمز بسيط أي شخص يقدر يستخدمه فورًا لو سمعه بالصدفة.

نصيحة إضافية: غيّر RECOVERY_SECRET بالأسفل لقيمة عشوائية طويلة من عندك
(مو النص الموجود حاليًا)، واحتفظ بنسخة من هذا الملف بمكان خاص عندك بعيد
عن أي كود تشاركه مع غيرك.
"""
import hmac
import hashlib

# غيّرها لقيمة عشوائية طويلة خاصة فيك (مثلاً 32+ حرف عشوائي) قبل ما توزّع
# البرنامج فعليًا على عملاء حقيقيين - هذا مجرد مثال افتراضي.
RECOVERY_SECRET = b"CHANGE-THIS-TO-YOUR-OWN-LONG-RANDOM-SECRET-BEFORE-SHIPPING"


def generate_recovery_code(device_id: str) -> str:
    """يحسب رمز استرجاع خاص بجهاز معيّن - نفس الدالة يستخدمها الفحص هنا
    وأداة generate_recovery_code.py المنفصلة اللي تشغّلها إنت بس."""
    mac = hmac.new(RECOVERY_SECRET, device_id.strip().encode("utf-8"), hashlib.sha256).hexdigest()
    return mac[:8].upper()


def verify_recovery_code(device_id: str, entered_code: str) -> bool:
    if not entered_code:
        return False
    expected = generate_recovery_code(device_id)
    return hmac.compare_digest(expected, entered_code.strip().upper())
